#!/usr/bin/env node
'use strict';
/**
 * Builds assets/icons/*.png (alpha masks, colored at run time with tintColor)
 * and src/icons.ts (static require() map for Metro).
 *
 * Sources:
 *  - Lucide icons (ISC license) from the lucide-static npm package: the
 *    callout icons that Obsidian and the Istari theme use.
 *  - Istari's own hand-drawn icons (MIT, TheScholium/istari), section 11 of
 *    theme.css, and the four-pointed star ornament of section 10c.
 *
 * Usage: node tools/make-ui-icons.js <lucide icons dir> <istari theme.css>
 */
const fs = require('fs');
const path = require('path');
const {rasterizeSvg} = require('../engine/svgicon');

const SIZE = 64;
const [lucideDir, istariCss] = process.argv.slice(2);
if (!lucideDir || !istariCss) {
  console.error('Usage: node tools/make-ui-icons.js <lucide-static/icons> <istari/theme.css>');
  process.exit(2);
}

const LUCIDE = [
  'scroll-text', 'book-open', 'feather', 'pen-tool', 'flask-conical', 'quote', 'anchor', 'sparkles', 'eye', 'target',
  'pencil', 'clipboard-list', 'info', 'circle-check', 'flame', 'check', 'circle-help', 'triangle-alert', 'x', 'zap',
  'bug', 'list', 'chevron-down', 'chevron-right', 'arrow-left', 'folder', 'file-text', 'image',
];

// Order of the --ist-icon declarations in theme.css section 11.
const ISTARI = [
  'scroll', 'loupe', 'codex', 'black-hole', 'tapestry', 'window', 'alembic', 'key', 'cauldron', 'compass',
  'hourglass', 'spectacles', 'banner', 'chain-in', 'chain-out',
];

const outDir = path.join(__dirname, '..', 'assets', 'icons');
fs.mkdirSync(outDir, {recursive: true});
const written = [];
function put(name, svg, opts) {
  fs.writeFileSync(path.join(outDir, name + '.png'), rasterizeSvg(svg, SIZE, opts));
  written.push(name);
}

for (const n of LUCIDE) {
  const svg = fs.readFileSync(path.join(lucideDir, n + '.svg'), 'utf8');
  put('lucide-' + n, svg, {strokeWidth: 1.5}); // Istari draws callout icons at 1.5
}

const css = fs.readFileSync(istariCss, 'utf8');
const sec = css.slice(css.indexOf('11. Icons'));
const uris = [...sec.matchAll(/--ist-icon:\s*url\("data:image\/svg\+xml,([^"]+)"\)/g)].map(m => decodeURIComponent(m[1]));
if (uris.length < ISTARI.length) throw new Error('Found ' + uris.length + ' Istari icons, expected ' + ISTARI.length);
ISTARI.forEach((n, i) => put('istari-' + n, uris[i]));

const star = css.match(/h2::before[\s\S]*?url\("data:image\/svg\+xml,([^"]+)"\)/);
if (!star) throw new Error('Star ornament not found');
put('istari-star', decodeURIComponent(star[1]));

const lines = written.map(n => `  '${n}': require('../assets/icons/${n}.png'),`);
fs.writeFileSync(
  path.join(__dirname, '..', 'src', 'icons.ts'),
  `/* Generated by tools/make-ui-icons.js. Do not edit. */\n` +
    `/* eslint-disable */\nexport const ICONS = {\n${lines.join('\n')}\n} as const;\n\n` +
    `export type IconName = keyof typeof ICONS;\n`,
);
console.log('Wrote ' + written.length + ' icons to ' + outDir);
